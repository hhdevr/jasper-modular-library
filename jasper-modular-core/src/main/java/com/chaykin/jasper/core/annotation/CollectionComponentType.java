package com.chaykin.jasper.core.annotation;

/**
 * JRXML component type generated for a {@link java.util.Collection}-typed field, via {@link JasperCollection#type()}.
 */
public enum CollectionComponentType {

    /**
     * Generates a JasperReports {@code list} component.
     */
    LIST,

    /**
     * Generates a JasperReports {@code table} component (the default).
     */
    TABLE
}
